"""
    某奶茶店记录了 5 名店员的奶茶销量（单位：杯）：

      店员  	周销量
      陈晨  	152
      刘倩  	178
      王浩  	143
      李娜  	165
      赵磊  	187

    请编写代码：

    1. 用字典列表（list[dict]）的方式构造 DataFrame df
    2. 分别计算周销量的最高值、最低值、平均值（平均值保留 1 位小数）

"""

import pandas as pd
df = pd.DataFrame([
    {"店员": "陈晨", "周销量": 152},
    {"店员": "刘倩", "周销量": 178},
    {"店员": "王浩", "周销量": 143},
    {"店员": "李娜", "周销量": 165},
    {"店员": "赵磊", "周销量": 187}
])
print(df)
print(f"周销量的最高值：{df['周销量'].max()}，最低值：{df['周销量'].min()}，平均值：{round(df['周销量'].mean(), 1)}")
